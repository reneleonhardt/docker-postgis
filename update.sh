    fi
    fullVersion="$(printf '%s\n' "$versionListAmd64" | package_version "postgresql-${postgresVersionMain}" || true)"
    armFullVersion="$(printf '%s\n' "$versionListArm64" | package_version "postgresql-${postgresVersionMain}" || true)"
    if [ "$fullVersion" != "$armFullVersion" ]; then
        echo "ERROR: PostgreSQL ${postgresVersionMain} package differs between amd64 (${fullVersion:-missing}) and arm64 (${armFullVersion:-missing})"
        exit 1
    fi

    optimized=""
    debianPostgisMajMin=""
    if [ "master" == "$postgisVersion" ]; then
        postgisPackageName=""
        postgisFullVersion="$postgisVersion"
        postgisMajor=""
        postgisDocSrc="development: postgis, geos, proj, gdal"
    else
        postgisMajMin="$( echo "${postgisVersion}" | cut -d. -f1 ).$( echo "${postgisVersion}" | cut -d. -f2 )"
        echo "postgisMajMin=${postgisMajMin}"
        if [ "$postgisMajMin" = '3.7' ]; then
            addressStandardizerBuildHash="$addressStandardizerReleaseGitHash"
        fi

        postgisPackageName="postgresql-${postgresVersionMain}-postgis-${postgisDebPkgNameVersionSuffixes[${postgisMajMin}]}"
        postgisFullVersion="$(printf '%s\n' "$versionListAmd64" | package_version "$postgisPackageName" || true)"
        armPostgisFullVersion="$(printf '%s\n' "$versionListArm64" | package_version "$postgisPackageName" || true)"
        if [ "$postgisFullVersion" != "$armPostgisFullVersion" ]; then
            echo "ERROR: ${postgisPackageName} differs between amd64 (${postgisFullVersion:-missing}) and arm64 (${armPostgisFullVersion:-missing})"
            exit 1
        fi
        echo "postgisPackageName=${postgisPackageName}"
        echo "postgisFullVersion=${postgisFullVersion}"

        debianPostgisMajMin="$( echo "${postgisFullVersion}" | cut -d. -f1 ).$( echo "${postgisFullVersion}" | cut -d. -f2 )"

        if [ "$debianPostgisMajMin" == "$postgisMajMin" ]; then
            echo "debian postgis version is OK "
            postgisMajor="${postgisDebPkgNameVersionSuffixes[${postgisMajMin}]}"
            postgisDocSrc="${postgisFullVersion%%+*}"
        else
            echo "debian postgis is not updated, different .. "
            postgisFullVersion=""
            postgisMajor=""
            postgisDocSrc=""
        fi
    fi

    if [ "$postgisVersion" != "master" ] && [ -z "$postgisFullVersion" ]; then
        echo "PGDG does not have PostGIS ${postgisMajMin}; generating a source-built Debian image"
        sourceBuiltDebian=true
        srcArchiveVersion="$(select_postgis_source_version "$postgisMajMin")"
        postgisFullVersion="$srcArchiveVersion"
        postgisDocSrc="$srcArchiveVersion"
        srcSha256="$(curl_download "https://github.com/postgis/postgis/archive/${srcArchiveVersion}.tar.gz" | sha256sum | awk '{ print $1 }')"
    fi

    optimized="debian"
    if [[ "$version" =~ (alpha|beta|rc|master) || "$postgisFullVersion" =~ (alpha|beta|rc) ]]; then
        optimized="test"
    fi
    echo "optimized=$optimized"

    if [ "$postgisVersion" = "master" ]; then
        (
            set -x
            cat Dockerfile.master.template > "$version/Dockerfile"
            sed_in_place 's/%%TXT_AUTOGENERATED%%/'"$autogenerated"'/g; s/%%PG_MAJOR%%/'"$postgresVersion"'/g; s/%%POSTGIS_MAJOR%%/'"$postgisMajor"'/g; s/%%POSTGIS_VERSION%%/'"$postgisFullVersion"'/g; s/%%H3_VERSION%%/'"$h3PackageVersion"'/g; s/%%PGROUTING_VERSION%%/'"$pgroutingPackageVersion"'/g; s/%%CGAL_GIT_BRANCH%%/'"$cgalGitBranch"'/g; s/%%POSTGIS_GIT_HASH%%/'"$postgisGitHash"'/g; s/%%H3_PG_GIT_HASH%%/'"$h3PgGitHash"'/g; s/%%ADDRESS_STANDARDIZER_GIT_HASH%%/'"$addressStandardizerGitHash"'/g; s/%%TIGER_GEOCODER_VERSION%%/'"$tigerGeocoderVersion"'/g; s/%%TIGER_GEOCODER_SHA256%%/'"$tigerGeocoderSha256"'/g; s/%%CGAL_GIT_HASH%%/'"$cgalGitHash"'/g; s/%%SFCGAL_GIT_HASH%%/'"$sfcgalGitHash"'/g; s/%%PROJ_GIT_HASH%%/'"$projGitHash"'/g; s/%%GDAL_GIT_HASH%%/'"$gdalGitHash"'/g; s/%%GEOS_GIT_HASH%%/'"$geosGitHash"'/g; s/%%BOOST_VERSION%%/'"$boostVersion"'/g; s/%%BOOST_CHRONO_VERSION%%/'"$boostChronoVersion"'/g; s/%%DEBIAN_VERSION%%/'"$suite"'/g; s/%%LIBCURL_RUNTIME_PACKAGE%%/'"$curlRuntimePackage"'/g; s/%%CFITSIO_RUNTIME_PACKAGE%%/'"$cfitsioRuntimePackage"'/g; s/%%FYBA_RUNTIME_PACKAGE%%/'"$fybaRuntimePackage"'/g; s/%%HDF5_RUNTIME_PACKAGE%%/'"$hdf5RuntimePackage"'/g; s/%%KML_BASE_RUNTIME_PACKAGE%%/'"$kmlBaseRuntimePackage"'/g; s/%%KML_DOM_RUNTIME_PACKAGE%%/'"$kmlDomRuntimePackage"'/g; s/%%KML_ENGINE_RUNTIME_PACKAGE%%/'"$kmlEngineRuntimePackage"'/g; s/%%NLOHMANN_JSON_VERSION%%/'"$nlohmannJsonVersion"'/g;' "$version/Dockerfile"
            echo "| [postgis/postgis:${version}](${dockerhublink}${version}) | [Dockerfile](${githubrepolink}/${version}/Dockerfile) | debian:${suite} | ${postgresVersion} | ${postgisDocSrc} |" >> "$dockerlistsDir/_dockerlists_${optimized}.md"
        )
    elif [ "$sourceBuiltDebian" = true ]; then
        postgisMinor="${postgisMajMin#*.}"
        (
            set -x
            cat Dockerfile.source.template > "$version/Dockerfile"
            sed_in_place 's/%%TXT_AUTOGENERATED%%/'"$autogenerated"'/g; s/%%PG_MAJOR%%/'"$postgresVersion"'/g; s/%%POSTGIS_VERSION%%/'"$postgisFullVersion"'/g; s/%%POSTGIS_SOURCE_VERSION%%/'"$srcArchiveVersion"'/g; s/%%POSTGIS_SHA256%%/'"$srcSha256"'/g; s/%%POSTGIS_MINOR%%/'"$postgisMinor"'/g; s/%%H3_VERSION%%/'"$h3PackageVersion"'/g; s/%%PGROUTING_VERSION%%/'"$pgroutingPackageVersion"'/g; s/%%ADDRESS_STANDARDIZER_GIT_HASH%%/'"$addressStandardizerBuildHash"'/g; s/%%TIGER_GEOCODER_VERSION%%/'"$tigerGeocoderVersion"'/g; s/%%TIGER_GEOCODER_SHA256%%/'"$tigerGeocoderSha256"'/g; s/%%DEBIAN_VERSION%%/'"$suite"'/g; s/%%SFCGAL_RUNTIME_PACKAGE%%/'"$sfcgalRuntimePackage"'/g;' "$version/Dockerfile"
            echo "| [postgis/postgis:${version}](${dockerhublink}${version}) | [Dockerfile](${githubrepolink}/${version}/Dockerfile) | debian:${suite} | ${postgresVersion} | ${postgisDocSrc} (source) |" >> "$dockerlistsDir/_dockerlists_${optimized}.md"
        )
    else
        (
            set -x
            cat Dockerfile.template > "$version/Dockerfile"
            sed_in_place 's/%%TXT_AUTOGENERATED%%/'"$autogenerated"'/g; s/%%PG_MAJOR%%/'"$postgresVersion"'/g; s/%%POSTGIS_MAJOR%%/'"$postgisMajor"'/g; s/%%POSTGIS_VERSION%%/'"$postgisFullVersion"'/g; s/%%H3_VERSION%%/'"$h3PackageVersion"'/g; s/%%PGROUTING_VERSION%%/'"$pgroutingPackageVersion"'/g; s/%%CGAL_GIT_BRANCH%%/'"$cgalGitBranch"'/g; s/%%POSTGIS_GIT_HASH%%/'"$postgisGitHash"'/g; s/%%H3_PG_GIT_HASH%%/'"$h3PgGitHash"'/g; s/%%ADDRESS_STANDARDIZER_GIT_HASH%%/'"$addressStandardizerGitHash"'/g; s/%%TIGER_GEOCODER_VERSION%%/'"$tigerGeocoderVersion"'/g; s/%%TIGER_GEOCODER_SHA256%%/'"$tigerGeocoderSha256"'/g; s/%%CGAL_GIT_HASH%%/'"$cgalGitHash"'/g; s/%%SFCGAL_GIT_HASH%%/'"$sfcgalGitHash"'/g; s/%%PROJ_GIT_HASH%%/'"$projGitHash"'/g; s/%%GDAL_GIT_HASH%%/'"$gdalGitHash"'/g; s/%%GEOS_GIT_HASH%%/'"$geosGitHash"'/g; s/%%BOOST_VERSION%%/'"$boostVersion"'/g; s/%%BOOST_CHRONO_VERSION%%/'"$boostChronoVersion"'/g; s/%%DEBIAN_VERSION%%/'"$suite"'/g; s/%%LIBCURL_RUNTIME_PACKAGE%%/'"$curlRuntimePackage"'/g; s/%%CFITSIO_RUNTIME_PACKAGE%%/'"$cfitsioRuntimePackage"'/g; s/%%FYBA_RUNTIME_PACKAGE%%/'"$fybaRuntimePackage"'/g; s/%%HDF5_RUNTIME_PACKAGE%%/'"$hdf5RuntimePackage"'/g; s/%%KML_BASE_RUNTIME_PACKAGE%%/'"$kmlBaseRuntimePackage"'/g; s/%%KML_DOM_RUNTIME_PACKAGE%%/'"$kmlDomRuntimePackage"'/g; s/%%KML_ENGINE_RUNTIME_PACKAGE%%/'"$kmlEngineRuntimePackage"'/g; s/%%NLOHMANN_JSON_VERSION%%/'"$nlohmannJsonVersion"'/g;' "$version/Dockerfile"

            echo "| [postgis/postgis:${version}](${dockerhublink}${version}) | [Dockerfile](${githubrepolink}/${version}/Dockerfile) | debian:${suite} | ${postgresVersion} | ${postgisDocSrc} |" >> "$dockerlistsDir/_dockerlists_${optimized}.md"
        )
    fi

    if [ "master" == "$postgisVersion" ] && [ -d "$version/alpine" ]; then
        alpineSuite="$(alpine_suite_for "$postgresVersion")"
        srcVersion="master"
        srcArchiveVersion="$postgisGitHash"
        srcSha256="$(curl_download "https://github.com/postgis/postgis/archive/$srcArchiveVersion.tar.gz" | sha256sum | awk '{ print $1 }')"
        postgisDocSrc=$srcVersion
    elif [ "master" == "$postgisVersion" ]; then
        srcVersion=""
        srcArchiveVersion=""
        srcSha256=""
    elif [ -d "$version/alpine" ]; then
        alpineSuite="$(alpine_suite_for "$postgresVersion")"
        srcVersion="$(select_postgis_source_version "$postgisMajMin")"

        srcArchiveVersion="$srcVersion"
        srcSha256="$(curl_download "https://github.com/postgis/postgis/archive/$srcVersion.tar.gz" | sha256sum | awk '{ print $1 }')"
        echo "Selected PostGIS version for Alpine: ${srcVersion}"
        postgisDocSrc=$srcVersion
    else
        srcVersion="${postgisFullVersion%%+*}"
        srcArchiveVersion="$srcVersion"
        srcSha256="$(curl_download "https://github.com/postgis/postgis/archive/$srcVersion.tar.gz" | sha256sum | awk '{ print $1 }')"
        postgisDocSrc=$srcVersion
    fi

    pgroutingVersion=""
    pgroutingSha256=""
    if [ -f "$version/alpine/pgrouting-version.txt" ]; then
        pgroutingVersion="$(tr -d '[:space:]' < "$version/alpine/pgrouting-version.txt")"
        if [[ ! "$pgroutingVersion" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
            echo "ERROR: invalid pgRouting version for $version/alpine: $pgroutingVersion"
            exit 1
        fi
        if [ "$pgroutingVersion" != "$pgroutingLatestVersion" ]; then
            echo "Updating pgRouting version for $version/alpine: $pgroutingVersion -> $pgroutingLatestVersion"
            pgroutingVersion="$pgroutingLatestVersion"
            printf '%s\n' "$pgroutingVersion" > "$version/alpine/pgrouting-version.txt"
        fi
        pgroutingSha256="$(curl_download "https://github.com/pgRouting/pgrouting/releases/download/v${pgroutingVersion}/pgrouting-${pgroutingVersion}.tar.gz" | sha256sum | awk '{ print $1 }')"
    fi

    variant=alpine
    if [ -d "$version/$variant" ]; then
        (
            set -x
            if [ "$optimized" != "test" ]; then
              optimized="alpine"
            fi
            cp -p Dockerfile.alpine.template "$version/$variant/"
            mv "$version/$variant/Dockerfile.alpine.template" "$version/$variant/Dockerfile"
            addressStandardizerBuildHash="$addressStandardizerGitHash"
            if [ "$postgisVersion" != "master" ] && [ "$postgisMajMin" = '3.7' ]; then
                addressStandardizerBuildHash="$addressStandardizerReleaseGitHash"
            fi
            sed_in_place 's/%%TXT_AUTOGENERATED%%/'"$autogenerated"'/g; s/%%PG_MAJOR%%/'"$postgresVersion"'/g; s/%%POSTGIS_VERSION%%/'"$srcVersion"'/g; s/%%POSTGIS_SOURCE_VERSION%%/'"$srcArchiveVersion"'/g; s/%%POSTGIS_SHA256%%/'"$srcSha256"'/g; s/%%PGROUTING_VERSION%%/'"$pgroutingVersion"'/g; s/%%PGROUTING_SHA256%%/'"$pgroutingSha256"'/g; s/%%ADDRESS_STANDARDIZER_GIT_HASH%%/'"$addressStandardizerBuildHash"'/g; s/%%TIGER_GEOCODER_VERSION%%/'"$tigerGeocoderVersion"'/g; s/%%TIGER_GEOCODER_SHA256%%/'"$tigerGeocoderSha256"'/g; s/%%ALPINE_SUITE%%/'"$alpineSuite"'/g' "$version/$variant/Dockerfile"

            echo "| [postgis/postgis:${version}-${variant}](${dockerhublink}${version}-${variant}) | [Dockerfile](${githubrepolink}/${version}/${variant}/Dockerfile) | alpine:${alpineSuite} | ${postgresVersion} | ${postgisDocSrc} (source) |" >> "$dockerlistsDir/_dockerlists_${optimized}.md"
        )
    fi
done

