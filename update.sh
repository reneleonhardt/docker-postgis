declare -A suitePackageList=()
function package_version() {
    local package="$1"
    awk -F ': ' -v package="$package" '$1 == "Package" { pkg = $2 } $1 == "Version" && pkg == package { print $2; exit }'
}

for version in "${versions[@]}"; do
    IFS=- read -r postgresVersion postgisVersion <<< "$version"
    postgresVersionMain="$(echo "$postgresVersion" | awk -F 'alpha|beta|rc' '{print $1}')"

    echo " "
    echo "---- generate Dockerfile for $version ----"
    echo "postgresVersion=$postgresVersion"
    echo "postgisVersion=$postgisVersion"
    alpineSuite="$defaultAlpineSuite"

    if [ "master" == "$postgisVersion" ]; then
        tag='trixie-slim'
    elif [ "2.5" == "$postgisVersion" ]; then
        # PostGIS 2.5 is only available on Stretch; no newer Debian package exists.
        tag='stretch-slim'
    else
        tag="${debianSuiteByPostgis[$postgisVersion]:-${debianSuite[$postgresVersionMain]:-$defaultDebianSuite}}"
    fi
    suite="${tag%%-slim}"

    for arch in amd64 arm64; do
        packageKey="${suite}/${arch}"
        if [ -z "${suitePackageList["$packageKey"]:+isset}" ]; then
            suitePackageList["$packageKey"]="$(curl_download "${packagesBase}/${suite}-pgdg/main/binary-${arch}/Packages.bz2" | bunzip2)"
        fi
    done

    versionListAmd64="$(printf '%s\n%s\n' "${suitePackageList["${suite}/amd64"]}" "$(curl_download "${packagesBase}/${suite}-pgdg/${postgresVersionMain}/binary-amd64/Packages.bz2" | bunzip2)")"
    versionListArm64="$(printf '%s\n%s\n' "${suitePackageList["${suite}/arm64"]}" "$(curl_download "${packagesBase}/${suite}-pgdg/${postgresVersionMain}/binary-arm64/Packages.bz2" | bunzip2)")"
    h3PackageName="postgresql-${postgresVersionMain}-h3"
    h3VersionAmd64="$(printf '%s\n' "$versionListAmd64" | package_version "$h3PackageName" || true)"
    h3VersionArm64="$(printf '%s\n' "$versionListArm64" | package_version "$h3PackageName" || true)"
    if [ -n "$h3VersionAmd64" ] || [ -n "$h3VersionArm64" ]; then
        if [ "$h3VersionAmd64" != "$h3VersionArm64" ]; then
            echo "ERROR: ${h3PackageName} differs between amd64 (${h3VersionAmd64:-missing}) and arm64 (${h3VersionArm64:-missing})"
            exit 1
        fi
        h3PackageVersion="$h3VersionAmd64"
    else
        h3PackageVersion=""
        if [ "$postgisVersion" != "master" ]; then
            warning "official ${h3PackageName} package is unavailable for Debian ${suite}; generated smoke will keep H3 optional"
        fi
    fi
    pgroutingPackageName="postgresql-${postgresVersionMain}-pgrouting"
    pgroutingVersionAmd64="$(printf '%s\n' "$versionListAmd64" | package_version "$pgroutingPackageName" || true)"
    pgroutingVersionArm64="$(printf '%s\n' "$versionListArm64" | package_version "$pgroutingPackageName" || true)"
    if [ -n "$pgroutingVersionAmd64" ] || [ -n "$pgroutingVersionArm64" ]; then
        if [ "$pgroutingVersionAmd64" != "$pgroutingVersionArm64" ]; then
            echo "ERROR: ${pgroutingPackageName} differs between amd64 (${pgroutingVersionAmd64:-missing}) and arm64 (${pgroutingVersionArm64:-missing})"
            exit 1
        fi
        pgroutingPackageVersion="$pgroutingVersionAmd64"
    else
        pgroutingPackageVersion=""
        warning "official ${pgroutingPackageName} package is unavailable for Debian ${suite}; generated smoke will keep pgRouting optional"
    fi
    fullVersion="$(printf '%s\n' "$versionListAmd64" | package_version "postgresql-${postgresVersionMain}" || true)"
    armFullVersion="$(printf '%s\n' "$versionListArm64" | package_version "postgresql-${postgresVersionMain}" || true)"
    if [ "$fullVersion" != "$armFullVersion" ]; then
        echo "ERROR: PostgreSQL ${postgresVersionMain} package differs between amd64 (${fullVersion:-missing}) and arm64 (${armFullVersion:-missing})"
        exit 1
    fi

    if [ "$suite" = "bullseye" ]; then
        boostVersion="1.74.0"
        boostChronoVersion="1.74.0"
    elif [ "$suite" = "trixie" ]; then
        boostVersion="1.83.0"
        boostChronoVersion="1.83.0t64"
    else
        echo "Unknown debian version; stop"
        exit 1
    fi


    optimized=""
    if [[ "$version" =~ "alpha" || "$version" =~ "beta" || "$version" =~ "rc" || "$version" =~ "master" ]];
    then
        optimized="test"
    else
        optimized="debian"
    fi
    echo "optimized=$optimized"

    debianPostgisMajMin=""
    if [ "master" == "$postgisVersion" ]; then
        postgisPackageName=""
        postgisFullVersion="$postgisVersion"
        postgisMajor=""
        postgisDocSrc="development: postgis, geos, proj, gdal"
    else
        postgisMajMin="$( echo "${postgisVersion}" | cut -d. -f1 ).$( echo "${postgisVersion}" | cut -d. -f2 )"
        echo "postgisMajMin=${postgisMajMin}"

        postgisPackageName="postgresql-${postgresVersionMain}-postgis-${postgisDebPkgNameVersionSuffixes[${postgisMajMin}]}"
        postgisFullVersion="$(printf '%s\n' "$versionListAmd64" | package_version "$postgisPackageName" || true)"
        armPostgisFullVersion="$(printf '%s\n' "$versionListArm64" | package_version "$postgisPackageName" || true)"
        if [ "$postgisFullVersion" != "$armPostgisFullVersion" ]; then
            echo "ERROR: ${postgisPackageName} differs between amd64 (${postgisFullVersion:-missing}) and arm64 (${armPostgisFullVersion:-missing})"
            exit 1
        fi
        echo "postgisPackageName=${postgisPackageName}"
        echo "postgisFullVersion=${postgisFullVersion}"

        debianPostgisMajMin="$( echo "${postgisFullVersion}" | cut -d. -f1 ).$( echo "${postgisFullVersion}" | cut -d. -f2 )"

        if [ "$debianPostgisMajMin" == "$postgisMajMin" ]; then
            echo "debian postgis version is OK "
            postgisMajor="${postgisDebPkgNameVersionSuffixes[${postgisMajMin}]}"
            postgisDocSrc="${postgisFullVersion%%+*}"
        else
            echo "debian postgis is not updated, different .. "
            postgisFullVersion=""
            postgisMajor=""
            postgisDocSrc=""
        fi
    fi

    if [ -z "$postgisFullVersion" ]
    then
        echo "SKIP debian version";
        # Keep unavailable Debian combinations visible in the generated matrix.
        echo "# placeholder Dockerfile: Debian PGDG has no PostgreSQL ${postgresVersion} / PostGIS ${postgisMajMin} package." > "$version/Dockerfile"
        echo "# Generated by ./update.sh; the Alpine variant may still be available." >> "$version/Dockerfile"
        rm -f "$version/*.sh"
        rm -f "$version/*.md"
        # Select the exact PostGIS source version for Alpine.
        _postgisMinor=$(echo "$postgisMajMin" | cut -d. -f2)
        postgisFullVersion=$(echo "$postgis_all_v3_versions" | grep "^3\.${_postgisMinor}\." | grep -v '[a-zA-Z]' | version_reverse_sort | head -n 1 || true)
        if [[ -z "${postgisFullVersion}" ]]; then
            postgisFullVersion=$(echo "$postgis_all_v3_versions" | grep "^3\.${_postgisMinor}\." | version_reverse_sort | head -n 1 || true)
        fi
        postgisDocSrc=$postgisFullVersion
        echo "Selected PostGIS version for Alpine: ${postgisFullVersion}"
    else
        (
            set -x
            if [ "master" == "$postgisVersion" ]; then
              cat Dockerfile.master.template > "$version/Dockerfile"
            else
              cat Dockerfile.template        > "$version/Dockerfile"
            fi
            sed_in_place 's/%%TXT_AUTOGENERATED%%/'"$autogenerated"'/g; s/%%PG_MAJOR%%/'"$postgresVersion"'/g; s/%%POSTGIS_MAJOR%%/'"$postgisMajor"'/g; s/%%POSTGIS_VERSION%%/'"$postgisFullVersion"'/g; s/%%H3_VERSION%%/'"$h3PackageVersion"'/g; s/%%PGROUTING_VERSION%%/'"$pgroutingPackageVersion"'/g; s/%%CGAL_GIT_BRANCH%%/'"$cgalGitBranch"'/g; s/%%POSTGIS_GIT_HASH%%/'"$postgisGitHash"'/g; s/%%H3_PG_GIT_HASH%%/'"$h3PgGitHash"'/g; s/%%ADDRESS_STANDARDIZER_GIT_HASH%%/'"$addressStandardizerGitHash"'/g; s/%%TIGER_GEOCODER_VERSION%%/'"$tigerGeocoderVersion"'/g; s/%%TIGER_GEOCODER_SHA256%%/'"$tigerGeocoderSha256"'/g; s/%%CGAL_GIT_HASH%%/'"$cgalGitHash"'/g; s/%%SFCGAL_GIT_HASH%%/'"$sfcgalGitHash"'/g; s/%%PROJ_GIT_HASH%%/'"$projGitHash"'/g; s/%%GDAL_GIT_HASH%%/'"$gdalGitHash"'/g; s/%%GEOS_GIT_HASH%%/'"$geosGitHash"'/g; s/%%BOOST_VERSION%%/'"$boostVersion"'/g; s/%%BOOST_CHRONO_VERSION%%/'"$boostChronoVersion"'/g; s/%%DEBIAN_VERSION%%/'"$suite"'/g; s/%%NLOHMANN_JSON_VERSION%%/'"$nlohmannJsonVersion"'/g;' "$version/Dockerfile"

            echo "| [postgis/postgis:${version}](${dockerhublink}${version}) | [Dockerfile](${githubrepolink}/${version}/Dockerfile) | debian:${suite} | ${postgresVersion} | ${postgisDocSrc} |" >> _dockerlists_${optimized}.md
        )
    fi

    if [ "master" == "$postgisVersion" ] && [ -d "$version/alpine" ]; then
        alpineSuite="$(alpine_suite_for "$postgresVersion")"
        srcVersion="master"
        srcArchiveVersion="$postgisGitHash"
        srcSha256="$(curl_download "https://github.com/postgis/postgis/archive/$srcArchiveVersion.tar.gz" | sha256sum | awk '{ print $1 }')"
        postgisDocSrc=$srcVersion
    elif [ "master" == "$postgisVersion" ]; then
        srcVersion=""
        srcArchiveVersion=""
        srcSha256=""
    elif [ -d "$version/alpine" ]; then
        alpineSuite="$(alpine_suite_for "$postgresVersion")"
        _postgisMajor=$(echo "$postgisMajMin" | cut -d. -f1)
        _postgisMinor=$(echo "$postgisMajMin" | cut -d. -f2)

        srcVersion=$(echo "$postgis_all_v3_versions_array_string" | tr ' ' '\n' | grep "^${_postgisMajor}\.${_postgisMinor}\." | grep -v '[a-zA-Z]' | head -n 1 || true)

        if [ -z "$srcVersion" ]; then
            echo "No stable PostGIS release found for ${_postgisMajor}.${_postgisMinor}; using the matrix preview or package version"
            if [[ "$postgisVersion" =~ alpha|beta|rc ]]; then
                srcVersion="$postgisVersion"
            else
                srcVersion="${postgisFullVersion%%+*}"
            fi
        fi

        srcArchiveVersion="$srcVersion"
        srcSha256="$(curl_download "https://github.com/postgis/postgis/archive/$srcVersion.tar.gz" | sha256sum | awk '{ print $1 }')"
        echo "Selected PostGIS version for Alpine: ${srcVersion}"
        postgisDocSrc=$srcVersion
    else
        srcVersion="${postgisFullVersion%%+*}"
        srcArchiveVersion="$srcVersion"
        srcSha256="$(curl_download "https://github.com/postgis/postgis/archive/$srcVersion.tar.gz" | sha256sum | awk '{ print $1 }')"
        postgisDocSrc=$srcVersion
    fi

    pgroutingVersion=""
    pgroutingSha256=""
    if [ -f "$version/alpine/pgrouting-version.txt" ]; then
        pgroutingVersion="$(tr -d '[:space:]' < "$version/alpine/pgrouting-version.txt")"
        if [[ ! "$pgroutingVersion" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
            echo "ERROR: invalid pgRouting version for $version/alpine: $pgroutingVersion"
            exit 1
        fi
        if [ "$pgroutingVersion" != "$pgroutingLatestVersion" ]; then
            echo "Updating pgRouting version for $version/alpine: $pgroutingVersion -> $pgroutingLatestVersion"
            pgroutingVersion="$pgroutingLatestVersion"
            printf '%s\n' "$pgroutingVersion" > "$version/alpine/pgrouting-version.txt"
        fi
        pgroutingSha256="$(curl_download "https://github.com/pgRouting/pgrouting/releases/download/v${pgroutingVersion}/pgrouting-${pgroutingVersion}.tar.gz" | sha256sum | awk '{ print $1 }')"
    fi

    variant=alpine
    if [ -d "$version/$variant" ]; then
        (
            set -x
            if [ "$optimized" != "test" ]; then
              optimized="alpine"
            fi
            cp -p Dockerfile.alpine.template "$version/$variant/"
            mv "$version/$variant/Dockerfile.alpine.template" "$version/$variant/Dockerfile"
            sed_in_place 's/%%TXT_AUTOGENERATED%%/'"$autogenerated"'/g; s/%%PG_MAJOR%%/'"$postgresVersion"'/g; s/%%POSTGIS_VERSION%%/'"$srcVersion"'/g; s/%%POSTGIS_SOURCE_VERSION%%/'"$srcArchiveVersion"'/g; s/%%POSTGIS_SHA256%%/'"$srcSha256"'/g; s/%%PGROUTING_VERSION%%/'"$pgroutingVersion"'/g; s/%%PGROUTING_SHA256%%/'"$pgroutingSha256"'/g; s/%%ADDRESS_STANDARDIZER_GIT_HASH%%/'"$addressStandardizerGitHash"'/g; s/%%TIGER_GEOCODER_VERSION%%/'"$tigerGeocoderVersion"'/g; s/%%TIGER_GEOCODER_SHA256%%/'"$tigerGeocoderSha256"'/g; s/%%ALPINE_SUITE%%/'"$alpineSuite"'/g' "$version/$variant/Dockerfile"

            echo "| [postgis/postgis:${version}-${variant}](${dockerhublink}${version}-${variant}) | [Dockerfile](${githubrepolink}/${version}/${variant}/Dockerfile) | alpine:${alpineSuite} | ${postgresVersion} | ${postgisDocSrc} |" >> _dockerlists_${optimized}.md
        )
    fi
done

