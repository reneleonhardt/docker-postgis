declare -A suitePackageList=()
declare -A versionPackageList=()
function package_version() {
    local package="$1"
    awk -F ': ' -v package="$package" '$1 == "Package" { pkg = $2 } $1 == "Version" && pkg == package { print $2; exit }'
}

# Debian suites are tried in preference order, with the other supported suite
# available when PGDG has not published the requested package for that pair.
function debian_suite_candidates() {
    local postgresMajor="$1"
    local postgisVersion="${2:-}"
    local preferred="${debianSuite["$postgresMajor"]:-}"

    if [ -z "$preferred" ]; then
        return 1
    fi

    # Retain packaged PostGIS 3.5 images for PG14-17 while PGDG publishes them.
    if [ "$postgisVersion" = '3.5' ] && (( postgresMajor >= 14 && postgresMajor <= 17 )); then
        printf '%s\n' bullseye
    fi

    case "$preferred" in
        bookworm) printf '%s\n' bookworm trixie ;;
        trixie) printf '%s\n' trixie bookworm ;;
        *) return 1 ;;
    esac
}

function load_suite_package_metadata() {
    local suite="$1"
    local postgresMajor="$2"
    local arch packageKey packageList

    for arch in amd64 arm64; do
        packageKey="${suite}/${arch}"
        if [ -z "${suitePackageList["$packageKey"]+set}" ]; then
            if ! packageList="$(curl_download "${packagesBase}/${suite}-pgdg/main/binary-${arch}/Packages.bz2" | bunzip2)"; then
                return 1
            fi
            suitePackageList["$packageKey"]="$packageList"
        fi

        packageKey="${suite}/${postgresMajor}/${arch}"
        if [ -z "${versionPackageList["$packageKey"]+set}" ]; then
            if packageList="$(curl_download "${packagesBase}/${suite}-pgdg/${postgresMajor}/binary-${arch}/Packages.bz2" | bunzip2)"; then
                versionPackageList["$packageKey"]="$packageList"
            else
                versionPackageList["$packageKey"]=''
            fi
        fi
    done

    versionListAmd64="$(printf '%s\n%s\n' "${suitePackageList["${suite}/amd64"]}" "${versionPackageList["${suite}/${postgresMajor}/amd64"]}")"
    versionListArm64="$(printf '%s\n%s\n' "${suitePackageList["${suite}/arm64"]}" "${versionPackageList["${suite}/${postgresMajor}/arm64"]}")"
}

function select_debian_suite() {
    local postgresMajor="$1"
    local postgisVersion="$2"
    local candidateList candidateSuites suite postgresA postgresB postgisA postgisB
    local fallbackSuite='' mismatchMessage=''
    local postgisSeries='' postgisPackageSuffix='' postgisPackageName=''
    local -a candidates=()
    selectedSuite=''

    if [ "$postgisVersion" != master ]; then
        postgisSeries="$(printf '%s\n' "$postgisVersion" | sed -E 's/^([0-9]+\.[0-9]+).*/\1/')"
        postgisPackageSuffix="${postgisDebPkgNameVersionSuffixes["$postgisSeries"]:-}"
        if [ -z "$postgisPackageSuffix" ]; then
            echo "ERROR: no Debian PGDG package mapping for PostGIS ${postgisSeries}" >&2
            return 1
        fi
        postgisPackageName="postgresql-${postgresMajor}-postgis-${postgisPackageSuffix}"
    fi

    if ! candidateList="$(debian_suite_candidates "$postgresMajor" "$postgisVersion")"; then
        echo "ERROR: no supported Debian suite mapping for PostgreSQL ${postgresMajor} / PostGIS ${postgisVersion}" >&2
        return 1
    fi
    mapfile -t candidates <<< "$candidateList"

    for suite in "${candidates[@]}"; do
        if ! load_suite_package_metadata "$suite" "$postgresMajor"; then
            continue
        fi
        postgresA="$(printf '%s\n' "$versionListAmd64" | package_version "postgresql-${postgresMajor}" || true)"
        postgresB="$(printf '%s\n' "$versionListArm64" | package_version "postgresql-${postgresMajor}" || true)"
        if [ "$postgresA" != "$postgresB" ]; then
            mismatchMessage="PostgreSQL ${postgresMajor} differs between amd64 (${postgresA:-missing}) and arm64 (${postgresB:-missing}) in Debian ${suite}"
            continue
        fi
        if [ -z "$postgresA" ]; then
            continue
        fi
        if [ "$postgisVersion" = master ]; then
            if [ -z "$fallbackSuite" ] && [ "$suite" != bullseye ]; then
                fallbackSuite="$suite"
            fi
            selectedSuite="$suite"
            break
        fi

        postgisA="$(printf '%s\n' "$versionListAmd64" | package_version "$postgisPackageName" || true)"
        postgisB="$(printf '%s\n' "$versionListArm64" | package_version "$postgisPackageName" || true)"
        if [ "$postgisA" != "$postgisB" ]; then
            mismatchMessage="${postgisPackageName} differs between amd64 (${postgisA:-missing}) and arm64 (${postgisB:-missing}) in Debian ${suite}"
            continue
        fi
        # Bullseye is package-only; source builds must use a supported suite.
        if [ -z "$fallbackSuite" ] && [ "$suite" != bullseye ]; then
            fallbackSuite="$suite"
        fi
        if [ -n "$postgisA" ]; then
            local packageSeries
            packageSeries="$(printf '%s\n' "$postgisA" | cut -d. -f1-2)"
            if [ "$packageSeries" = "$postgisSeries" ]; then
                selectedSuite="$suite"
                break
            fi
        fi
    done

    if [ -z "${selectedSuite:-}" ]; then
        if [ -z "$fallbackSuite" ]; then
            if [ -n "$mismatchMessage" ]; then
                echo "ERROR: ${mismatchMessage}" >&2
                return 1
            fi
            candidateSuites="$(printf '%s, ' "${candidates[@]}")"
            candidateSuites="${candidateSuites%, }"
            echo "ERROR: PostgreSQL ${postgresMajor} package is unavailable on both amd64 and arm64 in ${candidateSuites}" >&2
            return 1
        fi
        selectedSuite="$fallbackSuite"
    fi

    if ! load_suite_package_metadata "$selectedSuite" "$postgresMajor"; then
        echo "ERROR: unable to load PGDG metadata for Debian ${selectedSuite}" >&2
        return 1
    fi
}

