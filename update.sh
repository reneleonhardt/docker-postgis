# Correct version sorting
function version_reverse_sort() {
    # This function sorts version numbers in reverse order,
    # ensuring that versions without pre-release tags (e.g., "3.4.0")
    # are ranked higher than those with pre-release tags (e.g., "3.4.0rc4").
    # It adds a ".9991" suffix to versions without pre-release tags,
    # sorts them with `sort -Vr`, and then removes the ".9991" suffix.
    sed -r "s/([0-9]+\.[0-9]+\.[0-9]+$)/\1\.9991/" | sort -Vr | sed s/\.9991$//
}

api_preference="github"
function fetch_postgis_versions() {
    # get all postgis versions from github
    local REPO="postgis/postgis"
    local PER_PAGE=100 # You can ask for up to 100 results per page
    local page=1
    postgis_all_v3_versions=""

    while true; do
        local response
        if [ "$api_preference" == "github" ]; then
            response=$(curl_download "https://api.github.com/repos/$REPO/tags?per_page=$PER_PAGE&page=$page") || {
                echo "Failed to fetch postgis_versions from api.github.com/repos/$REPO/tags"
                return 1
            }
        elif [ "$api_preference" == "osgeo" ]; then
            response=$(curl_download "https://git.osgeo.org/gitea/api/v1/repos/${REPO}/tags?page=$page&limit=$PER_PAGE") || {
                echo "Failed to fetch postgis_versions from git.osgeo.org/gitea/api/v1/repos/${REPO}/tags"
                return 1
            }
        fi

        # Check for rate limit exceeded error - related to api.github.com
        if echo "$response" | grep -q "API rate limit exceeded"; then
            echo "Error: API rate limit exceeded!"
            echo "$response"
            exit 1
        fi

        # Extract tag names from the JSON response
        local tags
        tags=$(echo "$response" | sed -nE 's/.*"name":[[:space:]]*"([^"]+)".*/\1/p' || true)
        local count
        count=$(echo "$tags" | sed '/^$/d' | wc -l)

        if ((count == 0)); then
            break
        fi

        if ((page > 12)); then
            echo "Too many pages: ${page} - exiting; unexpected and something is wrong!"
            exit 1
        fi

        postgis_all_v3_versions+=" $tags"

        ((page++))
    done
}

fetch_postgis_versions || {
    echo "Error fetching postgis versions! Maybe network or server error!"
    exit 1
}

# Keep 3.* versions only
postgis_all_v3_versions=$(echo "$postgis_all_v3_versions" | sed '/^$/d' | grep '^3\.' | version_reverse_sort)
postgis_all_v3_versions_array_string=$(echo "$postgis_all_v3_versions" | tr '\n' ' ')
echo "postgis_all_v3_versions_array_string = ${postgis_all_v3_versions_array_string}"
echo " "

officialPostgisReleaseTags="$(printf '%s\n' "$postgis_all_v3_versions" | grep -E '^3\.[0-9]+\.[0-9]+(alpha[0-9]+|beta[0-9]+|rc[0-9]+)?$' | version_reverse_sort || true)"
for upstreamPostgisTag in $officialPostgisReleaseTags; do
    upstreamPostgisSeries="$(printf '%s\n' "$upstreamPostgisTag" | sed -E 's/^([0-9]+\.[0-9]+)\..*$/\1/')"
    upstreamPostgisMinor="${upstreamPostgisSeries#3.}"
    isStablePostgisRelease=true
    if [[ "$upstreamPostgisTag" =~ alpha|beta|rc ]]; then
        isStablePostgisRelease=false
    fi
    knownPostgisSeriesPresent=false
    if printf '%s\n' "${knownPostgisSeries[@]}" | grep -Fxq "$upstreamPostgisSeries"; then
        knownPostgisSeriesPresent=true
    fi
    if printf '%s\n' "${knownStablePostgisSeries[@]}" | grep -Fxq "$upstreamPostgisSeries"; then
        continue
    fi
    if [ "$isStablePostgisRelease" = false ] && [ "$knownPostgisSeriesPresent" = true ]; then
        continue
    fi
    if [ "$knownPostgisSeriesPresent" = false ] && (( upstreamPostgisMinor <= maxKnownPostgisMinor )); then
        continue
    fi
    if ! printf '%s\n' "${warnedPostgisSeries[@]}" | grep -Fxq "$upstreamPostgisSeries"; then
        if [ "$isStablePostgisRelease" = true ] && [ "$knownPostgisSeriesPresent" = true ]; then
            warning "PostGIS release ${upstreamPostgisTag} is stable but the matrix only contains a prerelease for series ${upstreamPostgisSeries}; update.sh will not rename a directory"
        else
            warning "PostGIS series ${upstreamPostgisSeries} (latest discovered tag ${upstreamPostgisTag}) is not represented in the matrix; update.sh will not create or rename a directory"
        fi
        warnedPostgisSeries+=("$upstreamPostgisSeries")
    fi
done

declare -A alpineSuiteByPostgresTag=()
function alpine_suite_for() {
    local postgresTag="$1"
    local suites

    if [ -n "${alpineSuiteByPostgresTag["$postgresTag"]:+set}" ]; then
        printf '%s\n' "${alpineSuiteByPostgresTag["$postgresTag"]}"
        return
    fi

    suites="$(printf '%s\n' "$officialPostgresLibrary" | awk -v wanted="$postgresTag" '
        function reset() {
            tagMatch = 0
            architectureMatch = 0
            directory = ""
        }
        function finish(   suite) {
            if (!tagMatch || !architectureMatch || directory == "") {
                reset()
                return
            }
            suite = directory
            sub(/^.*\//, "", suite)
            sub(/^alpine/, "", suite)
            if (suite ~ /^3\.[0-9]+$/) {
                print suite
            }
            reset()
        }
        BEGIN { reset() }
        /^Tags:/ {
            sub(/^Tags:[[:space:]]*/, "")
            count = split($0, tags, /,[[:space:]]*/)
            for (i = 1; i <= count; i++) {
                if (tags[i] == wanted "-alpine" || tags[i] ~ ("^" wanted "-alpine3\\.[0-9]+$")) {
                    tagMatch = 1
                }
            }
            next
        }
        /^Architectures:/ {
            if ($0 ~ /amd64([,[:space:]]|$)/ && $0 ~ /arm64v8([,[:space:]]|$)/) {
                architectureMatch = 1
            }
            next
        }
        /^Directory:/ {
            sub(/^Directory:[[:space:]]*/, "")
            directory = $0
            next
        }
        /^$/ { finish() }
        END { finish() }
    ' | sort -Vu)"

    if [ -z "$suites" ]; then
        warning "no official Alpine image for PostgreSQL ${postgresTag} with amd64 and arm64v8 metadata; retaining Alpine ${defaultAlpineSuite} as an unverified fallback"
        suites="$defaultAlpineSuite"
    else
        suites="$(printf '%s\n' "$suites" | tail -n 1)"
    fi

    alpineSuiteByPostgresTag["$postgresTag"]="$suites"
    printf '%s\n' "$suites"
}

