function select_postgis_source_version() {
    local series="$1"
    local selected

    selected="$(printf '%s\n' "$postgis_all_v3_versions" | grep -E "^${series}\\.[0-9]+$" | version_reverse_sort | head -n 1 || true)"
    if [ -z "$selected" ]; then
        selected="$(printf '%s\n' "$postgis_all_v3_versions" | grep -E "^${series}\\.[0-9]+(alpha[0-9]+|beta[0-9]+|rc[0-9]+)$" | version_reverse_sort | head -n 1 || true)"
    fi
    if [ -z "$selected" ]; then
        echo "ERROR: no PostGIS source release found for series ${series}" >&2
        return 1
    fi
    printf '%s\n' "$selected"
}

