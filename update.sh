            if [ -f "$dockerfile" ] && grep -Eq '^ENV POSTGIS_VERSION=[^[:space:]]+$' "$dockerfile" && ! grep -Eq '^ENV POSTGIS_VERSION=.*(alpha|beta|rc)' "$dockerfile"; then
